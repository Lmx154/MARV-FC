//! The mission (waypoint list) service on the board (`docs/link-contract.md` of MARV-GCS, section 17; decision-mavlink-mode-20261123,
//! section 1 item C): `fw_core::mission::MissionService` in one critical-section static shared by both links, the
//! accept list, the wire decode and encode of the six messages, and one reply slot per link.
//!
//! Core 0 only. Nothing here runs on core 1 and nothing flies a list: the committed list reaches the shadow guidance through
//! `flight::push_gdn` (`GDN_SRC` 1), which core 1 takes on a disarmed step.
//!
//! Each link's task hands its mission frames to [`message`] (the USB task from its `receive_with` hook, the radio from the
//! port's `Hooks::mavlink`) and drains its reply slot through [`sample`], the sample of a stream slot of its node with the id
//! [`SLOT_ID`] (5 ms on USB, the log download's slot interval; 40 ms on the radio, the radio node's parameter-list interval,
//! a normal stream there: the radio's flow control lengthens it). [`sample`] also drives the service's timers, from whichever
//! link's slot is sampled, so a retry or a give-up fires whichever link owns the transaction; the message goes to the
//! owner's link's slot. A slot holds one message: a new one to the same destination replaces it, one to another destination
//! is dropped while one waits (the contract's "Reply pacing"). A message is handed to the slot, and the service's timers
//! start, when the service produces it.
//!
//! The service's armed input is false since packet H2 (Amendment A, A4): an upload or a clear is taken while armed.

use core::cell::RefCell;
use core::sync::atomic::{AtomicBool, AtomicU32, Ordering};

use embassy_sync::blocking_mutex::Mutex;
use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
use fw_core::mission::{
    MAX_ITEMS, Frame, Item, Link, MISSION_ACK_ID, MISSION_CLEAR_ALL_ID, MISSION_COUNT_ID,
    MISSION_ITEM_INT_ID, MISSION_REQUEST_INT_ID, MISSION_REQUEST_LIST_ID, MissionService, Tx,
    TxMsg, decode, result,
};
use mavlink_device::dialect::{
    MISSION_ACK_DATA, MISSION_COUNT_DATA, MISSION_ITEM_INT_DATA, MISSION_REQUEST_INT_DATA,
    MavCmd, MavFrame, MavMissionResult, MavMissionType,
};
use mavlink_device::{Incoming, Outgoing};

/// The six messages' (id, CRC_EXTRA) as generated by `marv-dialect` for `common` (`impl MessageData for MISSION_COUNT_DATA` and
/// the others; the trait is not reachable from this crate, so the values are copied, as `logdl::ACCEPT` does).
pub const ACCEPT: [(u32, u8); 6] = [
    (MISSION_REQUEST_LIST_ID, 132),
    (MISSION_COUNT_ID, 221),
    (MISSION_CLEAR_ALL_ID, 232),
    (MISSION_ACK_ID, 153),
    (MISSION_REQUEST_INT_ID, 196),
    (MISSION_ITEM_INT_ID, 38),
];

/// The id of the reply slot's stream: MISSION_ITEM_INT's. The slot carries whichever mission message waits.
pub const SLOT_ID: u32 = MISSION_ITEM_INT_ID;
/// The USB reply slot's interval: one mission message per 5 ms, as `logdl::INTERVAL_US`.
pub const USB_INTERVAL_US: i32 = crate::logdl::INTERVAL_US;
/// The radio reply slot's interval: one mission message per 40 ms (the radio node's parameter-list interval).
pub const RADIO_INTERVAL_US: i32 = 40_000;

struct State {
    svc: MissionService,
    /// The message waiting in each link's slot (`Link::Usb` 0, `Link::Radio` 1).
    slots: [Option<Tx>; 2],
}

static STATE: Mutex<CriticalSectionRawMutex, RefCell<State>> = Mutex::new(RefCell::new(State {
    svc: MissionService::new(),
    slots: [None, None],
}));

/// A transaction runs or a message waits: what [`sample`] checks before it takes the lock.
static ACTIVE: AtomicBool = AtomicBool::new(false);
/// The service's change counter, as of the last operation.
static CHANGES: AtomicU32 = AtomicU32::new(0);
/// The change counter of the copy `flight::push_gdn` last pushed.
static PUSHED: AtomicU32 = AtomicU32::new(0);

fn index(link: Link) -> usize {
    match link {
        Link::Usb => 0,
        Link::Radio => 1,
    }
}

/// Puts `tx` in its link's slot: empty slot, or a waiting message to the same system and component (replaced); a waiting
/// message to another destination keeps the slot and `tx` is dropped.
fn offer(slots: &mut [Option<Tx>; 2], tx: Tx) {
    if let Some(slot) = slots.get_mut(index(tx.link)) {
        match slot {
            Some(waiting)
                if waiting.dst_system != tx.dst_system
                    || waiting.dst_component != tx.dst_component => {}
            _ => *slot = Some(tx),
        }
    }
}

fn publish(st: &State) {
    ACTIVE.store(
        st.svc.busy() || st.slots.iter().any(Option::is_some),
        Ordering::Relaxed,
    );
    CHANGES.store(st.svc.change_counter(), Ordering::Relaxed);
}

/// A listed message from `link`'s node. `false` when its id is not one of the six (the caller has other listed messages).
/// The frame's targets are checked by the service.
pub fn message(link: Link, m: Incoming<'_>) -> bool {
    let Some((target_system, target_component, msg)) = decode(m.message_id, m.payload) else {
        return false;
    };
    let frame = Frame {
        link,
        src_system: m.system_id,
        src_component: m.component_id,
        target_system,
        target_component,
        msg,
    };
    // Amendment A (A4, packet H2): MISSION_COUNT, MISSION_CLEAR_ALL and the items of an upload are no longer refused
    // while armed, in every state; a new plan id reaches the state machine through `station::push_plan`.
    let armed = false;
    // The height limits in force now, read before the lock is taken (the store is never nested in it). A value that cannot be
    // read or has the wrong type is NaN: every `z` is refused (fail closed).
    let (alt_min, alt_max) = crate::store::with(|p| {
        let get = |name| match p.get_named(name) {
            Some(mavlink_device::ParamValue::F32(v)) => v,
            _ => f32::NAN,
        };
        (get(fw_settings::flight::GDN_ALT_MIN), get(fw_settings::flight::GDN_ALT_MAX))
    })
    .unwrap_or((f32::NAN, f32::NAN));
    STATE.lock(|c| {
        let mut st = c.borrow_mut();
        st.svc.set_limits(alt_min, alt_max);
        if let Some(tx) = st.svc.handle(m.now_us, armed, &frame) {
            offer(&mut st.slots, tx);
        }
        publish(&st);
    });
    true
}

/// The reply slot's sample for `link`'s node: runs the service's timers, then pushes the message waiting in `link`'s slot, if
/// any. With no transaction and nothing waiting it is one relaxed load.
pub fn sample(link: Link, now_us: u64, out: &mut Outgoing<'_>) -> bool {
    if !ACTIVE.load(Ordering::Relaxed) {
        return false;
    }
    let tx = STATE.lock(|c| {
        let mut st = c.borrow_mut();
        if let Some(tx) = st.svc.poll(now_us) {
            offer(&mut st.slots, tx);
        }
        let waiting = st.slots.get_mut(index(link)).and_then(Option::take);
        publish(&st);
        waiting
    });
    tx.is_some_and(|tx| push(&tx, out))
}

/// `link` went down (USB closed or the node stopped; the radio port left its MAVLink lock): its transaction ends at once,
/// the message waiting in its slot is dropped, and the last upload of an owner on it is forgotten.
pub fn link_down(link: Link) {
    STATE.lock(|c| {
        let mut st = c.borrow_mut();
        st.svc.link_down(link);
        if let Some(slot) = st.slots.get_mut(index(link)) {
            *slot = None;
        }
        publish(&st);
    });
}

/// A copy of the committed list (the waypoints and the return item), its length, the change counter and the plan id, for
/// `flight::push_gdn`.
pub fn committed() -> ([Item; MAX_ITEMS], usize, u32, u32) {
    STATE.lock(|c| {
        let st = c.borrow();
        let mut items = [Item::default(); MAX_ITEMS];
        for (dst, src) in items.iter_mut().zip(st.svc.items()) {
            *dst = *src;
        }
        (items, st.svc.items().len(), st.svc.change_counter(), st.svc.plan_id())
    })
}

/// `flight::push_gdn` pushed the copy taken at change counter `changes`.
pub fn note_pushed(changes: u32) {
    PUSHED.store(changes, Ordering::Relaxed);
}

/// The mission's change counter moved since the last push (two relaxed loads).
pub fn changed() -> bool {
    CHANGES.load(Ordering::Relaxed) != PUSHED.load(Ordering::Relaxed)
}

fn result_code(r: u8) -> MavMissionResult {
    match r {
        result::ACCEPTED => MavMissionResult::MAV_MISSION_ACCEPTED,
        result::UNSUPPORTED_FRAME => MavMissionResult::MAV_MISSION_UNSUPPORTED_FRAME,
        result::UNSUPPORTED => MavMissionResult::MAV_MISSION_UNSUPPORTED,
        result::NO_SPACE => MavMissionResult::MAV_MISSION_NO_SPACE,
        result::INVALID => MavMissionResult::MAV_MISSION_INVALID,
        result::INVALID_PARAM5_X => MavMissionResult::MAV_MISSION_INVALID_PARAM5_X,
        result::INVALID_PARAM6_Y => MavMissionResult::MAV_MISSION_INVALID_PARAM6_Y,
        result::INVALID_PARAM7 => MavMissionResult::MAV_MISSION_INVALID_PARAM7,
        result::INVALID_SEQUENCE => MavMissionResult::MAV_MISSION_INVALID_SEQUENCE,
        result::DENIED => MavMissionResult::MAV_MISSION_DENIED,
        result::OPERATION_CANCELLED => MavMissionResult::MAV_MISSION_OPERATION_CANCELLED,
        _ => MavMissionResult::MAV_MISSION_ERROR,
    }
}

/// The plan type of an answer. A value the dialect's enum cannot carry (a station's `mission_type` 7, which the vehicle refused as
/// UNSUPPORTED) is answered as 0: `Outgoing` takes typed messages only.
fn plan_type(t: u8) -> MavMissionType {
    match t {
        1 => MavMissionType::MAV_MISSION_TYPE_FENCE,
        2 => MavMissionType::MAV_MISSION_TYPE_RALLY,
        255 => MavMissionType::MAV_MISSION_TYPE_ALL,
        _ => MavMissionType::MAV_MISSION_TYPE_MISSION,
    }
}

/// Encodes `tx`: MISSION_REQUEST_INT, MISSION_COUNT, MISSION_ACK or MISSION_ITEM_INT (frame 3, command 16, or 20 for the return item, `current` 0,
/// `autocontinue` 1, `param1` to `param4` 0.0, `mission_type` 0).
fn push(tx: &Tx, out: &mut Outgoing<'_>) -> bool {
    let (target_system, target_component) = (tx.dst_system, tx.dst_component);
    match tx.msg {
        TxMsg::RequestInt { seq } => out
            .push(&MISSION_REQUEST_INT_DATA {
                seq,
                target_system,
                target_component,
                mission_type: MavMissionType::MAV_MISSION_TYPE_MISSION,
            })
            .is_ok(),
        TxMsg::Count { count, opaque_id } => out
            .push(&MISSION_COUNT_DATA {
                count,
                target_system,
                target_component,
                mission_type: MavMissionType::MAV_MISSION_TYPE_MISSION,
                opaque_id,
            })
            .is_ok(),
        TxMsg::Ack { result, mission_type, opaque_id } => out
            .push(&MISSION_ACK_DATA {
                target_system,
                target_component,
                mavtype: result_code(result),
                mission_type: plan_type(mission_type),
                opaque_id,
            })
            .is_ok(),
        TxMsg::ReturnItem { seq, z_bits } => out
            .push(&MISSION_ITEM_INT_DATA {
                param1: 0.0,
                param2: 0.0,
                param3: 0.0,
                param4: 0.0,
                x: 0,
                y: 0,
                z: f32::from_bits(z_bits),
                seq,
                command: MavCmd::MAV_CMD_NAV_RETURN_TO_LAUNCH,
                target_system,
                target_component,
                frame: MavFrame::MAV_FRAME_GLOBAL_RELATIVE_ALT,
                current: 0,
                autocontinue: 1,
                mission_type: MavMissionType::MAV_MISSION_TYPE_MISSION,
            })
            .is_ok(),
        TxMsg::Item { seq, x, y, z_bits } => out
            .push(&MISSION_ITEM_INT_DATA {
                param1: 0.0,
                param2: 0.0,
                param3: 0.0,
                param4: 0.0,
                x,
                y,
                z: f32::from_bits(z_bits),
                seq,
                command: MavCmd::MAV_CMD_NAV_WAYPOINT,
                target_system,
                target_component,
                frame: MavFrame::MAV_FRAME_GLOBAL_RELATIVE_ALT,
                current: 0,
                autocontinue: 1,
                mission_type: MavMissionType::MAV_MISSION_TYPE_MISSION,
            })
            .is_ok(),
    }
}
