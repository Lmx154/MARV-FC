//! Log download over USB: ArduPilot's LOG_REQUEST_LIST, LOG_ENTRY, LOG_REQUEST_DATA, LOG_DATA and LOG_REQUEST_END, on the USB link only.
//! The USB task takes the requests from its node (`Usb::message`, through the accept list and `receive_with`), publishes each with a new generation number in `REQUEST` and wakes the SD task (`WAKE`).
//! The SD task, the only code that touches the card, answers through `HANDOVER`, an `ExtLogRing` (in the PSRAM) of whole records each tagged with the generation it answers;
//! the USB task sends them through its LOG_DATA stream slot, at most 4 frames per sample (`Usb::sample`), and drops every record of an older generation, so a replaced or ended transfer's bytes are never sent.

use core::cell::Cell;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_sync::blocking_mutex::Mutex;
use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
use embassy_sync::signal::Signal;
use fw_core::extring::{ExtLogRing, LogConsumer, LogProducer};
use mavlink_device::dialect::{
    LOG_DATA_DATA, LOG_ENTRY_DATA, LOG_REQUEST_DATA_DATA, LOG_REQUEST_END_DATA,
    LOG_REQUEST_LIST_DATA,
};
use mavlink_device::{Incoming, MAX_BATCH, Outgoing};

pub const LOG_REQUEST_LIST_ID: u32 = 117;
pub const LOG_REQUEST_DATA_ID: u32 = 119;
pub const LOG_DATA_ID: u32 = 120;
pub const LOG_REQUEST_END_ID: u32 = 122;
/// The USB node's accept list: (id, CRC_EXTRA) as generated by `marv-dialect`; copied because the `MessageData` trait is not reachable from this crate.
pub const ACCEPT: [(u32, u8); 3] = [
    (LOG_REQUEST_LIST_ID, 128),
    (LOG_REQUEST_DATA_ID, 116),
    (LOG_REQUEST_END_ID, 203),
];
/// The LOG_DATA slot's interval: at most `MAX_BATCH` frames per 5 ms.
pub const INTERVAL_US: i32 = 5_000;
/// A transfer stops when the station's HEARTBEAT is this old (the USB node's `gcs_timeout_us`).
pub const GCS_TIMEOUT_US: u64 = 3_000_000;

pub const HANDOVER_BYTES: usize = 4096;
/// SD task -> USB task: whole records (`push_data`, `push_entry`). Its storage is `psram::HANDOVER_BUF`, bound by `psram::init`;
/// unbound without a working PSRAM, and then the download is refused (`Usb::message`).
pub static HANDOVER: ExtLogRing<HANDOVER_BYTES> = ExtLogRing::new();
static REQUEST: Mutex<CriticalSectionRawMutex, Cell<(u32, Request)>> =
    Mutex::new(Cell::new((0, Request::Stop)));
/// Wakes the SD task: a new request, or room made in `HANDOVER`.
pub static WAKE: Signal<CriticalSectionRawMutex, ()> = Signal::new();

pub static TRANSFERS: AtomicU32 = AtomicU32::new(0);
pub static BYTES_SENT: AtomicU32 = AtomicU32::new(0);
/// The SD task's longest download step, in microseconds.
pub static STEP_MAX_US: AtomicU32 = AtomicU32::new(0);
/// The longest time a log piece or flush waited for a download step, in microseconds (an upper
/// bound: the step's whole duration when something was due after it).
pub static LATE_MAX_US: AtomicU32 = AtomicU32::new(0);

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Request {
    /// Nothing (LOG_REQUEST_END, the station's HEARTBEAT lost, the link down).
    Stop,
    List {
        start: u16,
        end: u16,
    },
    Data {
        id: u16,
        ofs: u32,
        count: u32,
    },
}

pub fn request() -> (u32, Request) {
    REQUEST.lock(Cell::get)
}

pub const CHUNK: usize = 90;
const TAG_DATA: u8 = 0;
const TAG_ENTRY: u8 = 1;
/// Tag, generation, id, offset, count.
pub const DATA_HEADER: usize = 12;
/// Tag, generation, id, num_logs, last_log_num, size.
pub const ENTRY_LEN: usize = 15;
const RECORD_MAX: usize = DATA_HEADER + CHUNK;

/// One LOG_DATA record: `data` at most `CHUNK` bytes (empty: the end marker). `false` if it does
/// not fit.
pub fn push_data(
    p: &mut LogProducer<'_, HANDOVER_BYTES>,
    generation: u32,
    id: u16,
    ofs: u32,
    data: &[u8],
) -> bool {
    let n = data.len().min(CHUNK);
    let mut rec = [0u8; RECORD_MAX];
    rec[0] = TAG_DATA;
    rec[1..5].copy_from_slice(&generation.to_le_bytes());
    rec[5..7].copy_from_slice(&id.to_le_bytes());
    rec[7..11].copy_from_slice(&ofs.to_le_bytes());
    rec[11] = n as u8;
    if let (Some(dst), Some(src)) = (rec.get_mut(DATA_HEADER..DATA_HEADER + n), data.get(..n)) {
        dst.copy_from_slice(src);
    }
    p.push(rec.get(..DATA_HEADER + n).unwrap_or(&[]))
}

pub fn push_entry(
    p: &mut LogProducer<'_, HANDOVER_BYTES>,
    generation: u32,
    id: u16,
    num_logs: u16,
    last_log_num: u16,
    size: u32,
) -> bool {
    let mut rec = [0u8; ENTRY_LEN];
    rec[0] = TAG_ENTRY;
    rec[1..5].copy_from_slice(&generation.to_le_bytes());
    rec[5..7].copy_from_slice(&id.to_le_bytes());
    rec[7..9].copy_from_slice(&num_logs.to_le_bytes());
    rec[9..11].copy_from_slice(&last_log_num.to_le_bytes());
    rec[11..15].copy_from_slice(&size.to_le_bytes());
    p.push(&rec)
}

fn le16(b: &[u8], at: usize) -> u16 {
    b.get(at..at + 2)
        .and_then(|s| s.try_into().ok())
        .map_or(0, u16::from_le_bytes)
}

fn le32(b: &[u8], at: usize) -> u32 {
    b.get(at..at + 4)
        .and_then(|s| s.try_into().ok())
        .map_or(0, u32::from_le_bytes)
}

pub struct Usb {
    consumer: Option<LogConsumer<'static, HANDOVER_BYTES>>,
    generation: u32,
    active: bool,
    system_id: u8,
    component_id: u8,
}

impl Usb {
    pub fn new(system_id: u8, component_id: u8) -> Self {
        Self {
            consumer: HANDOVER.take_consumer(),
            generation: 0,
            active: false,
            system_id,
            component_id,
        }
    }

    /// A listed message from `receive_with`; a request not addressed to this node (its target
    /// system or component neither the node's nor 0) is dropped.
    pub fn message(&mut self, m: Incoming<'_>) {
        // No PSRAM (the ring is unbound), or a FAULT since: a listing or a download cannot be answered, so it is
        // refused here (no generation, no wake of the SD task). A request to end is still taken.
        let usable = self.consumer.is_some() && crate::psram::ready();
        let for_us = |system: u8, component: u8| {
            (system == 0 || system == self.system_id)
                && (component == 0 || component == self.component_id)
        };
        match m.message_id {
            LOG_REQUEST_LIST_ID if usable => {
                if let Some(r) = m.decode::<LOG_REQUEST_LIST_DATA>()
                    && for_us(r.target_system, r.target_component)
                {
                    self.start(Request::List {
                        start: r.start,
                        end: r.end,
                    });
                }
            }
            LOG_REQUEST_DATA_ID if usable => {
                if let Some(r) = m.decode::<LOG_REQUEST_DATA_DATA>()
                    && for_us(r.target_system, r.target_component)
                {
                    TRANSFERS.fetch_add(1, Ordering::Relaxed);
                    self.start(Request::Data {
                        id: r.id,
                        ofs: r.ofs,
                        count: r.count,
                    });
                }
            }
            LOG_REQUEST_END_ID => {
                if let Some(r) = m.decode::<LOG_REQUEST_END_DATA>()
                    && for_us(r.target_system, r.target_component)
                {
                    self.stop();
                }
            }
            _ => {}
        }
    }

    fn start(&mut self, request: Request) {
        self.generation = self.generation.wrapping_add(1);
        let generation = self.generation;
        REQUEST.lock(|c| c.set((generation, request)));
        self.active = true;
        WAKE.signal(());
    }

    pub fn stop(&mut self) {
        if self.active {
            self.start(Request::Stop);
            self.active = false;
        }
    }

    /// The LOG_DATA slot's sample: up to `MAX_BATCH` LOG_DATA or LOG_ENTRY frames of the current
    /// generation; records of older generations are dropped on the way.
    pub fn sample(&mut self, out: &mut Outgoing<'_>) -> bool {
        // Once per sample, before the first PSRAM read: not after a FAULT.
        if !crate::psram::ready() {
            return false;
        }
        let Some(consumer) = self.consumer.as_mut() else {
            return false;
        };
        let mut pushed = 0;
        let mut took = false;
        for _ in 0..HANDOVER_BYTES / ENTRY_LEN {
            if pushed == MAX_BATCH {
                break;
            }
            let mut rec = [0u8; RECORD_MAX];
            let (a, b) = consumer.peek_up_to(RECORD_MAX);
            if a.is_empty() {
                break;
            }
            let k = a.len().min(RECORD_MAX);
            if let (Some(dst), Some(src)) = (rec.get_mut(..k), a.get(..k)) {
                dst.copy_from_slice(src);
            }
            let m = b.len().min(RECORD_MAX - k);
            if let (Some(dst), Some(src)) = (rec.get_mut(k..k + m), b.get(..m)) {
                dst.copy_from_slice(src);
            }
            let tag = rec[0];
            let len = if tag == TAG_DATA {
                DATA_HEADER + usize::from(rec[11]).min(CHUNK)
            } else {
                ENTRY_LEN
            };
            if self.active && le32(&rec, 1) == self.generation {
                if tag == TAG_DATA {
                    let count = rec[11].min(CHUNK as u8);
                    let mut data = [0u8; CHUNK];
                    if let (Some(dst), Some(src)) = (
                        data.get_mut(..usize::from(count)),
                        rec.get(DATA_HEADER..DATA_HEADER + usize::from(count)),
                    ) {
                        dst.copy_from_slice(src);
                    }
                    let message = LOG_DATA_DATA {
                        ofs: le32(&rec, 7),
                        id: le16(&rec, 5),
                        count,
                        data,
                    };
                    if out.push(&message).is_ok() {
                        BYTES_SENT.fetch_add(u32::from(count), Ordering::Relaxed);
                    }
                } else {
                    let _ = out.push(&LOG_ENTRY_DATA {
                        time_utc: 0,
                        size: le32(&rec, 11),
                        id: le16(&rec, 5),
                        num_logs: le16(&rec, 7),
                        last_log_num: le16(&rec, 9),
                    });
                }
                pushed += 1;
            }
            consumer.consume(len);
            took = true;
        }
        if took {
            WAKE.signal(());
        }
        pushed > 0
    }
}
